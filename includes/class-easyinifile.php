<?php
/**
 * INIFile class for easy-php-settings plugin
 *
 * @package EasyPHPSettings
 * @since 1.0.0
 */

if ( ! defined( 'WPINC' ) ) {
	die;
}

/**
 * EasyIniFile class
 *
 * Handles INI file operations. The plugin owns only the lines between
 * MARKER_BEGIN and MARKER_END; anything else in .user.ini / php.ini
 * (for example the Wordfence WAF auto_prepend_file block) is preserved.
 *
 * @package EasyPHPSettings
 * @since 1.0.0
 */
class EasyIniFile {

	/**
	 * First line of the block this plugin manages.
	 */
	const MARKER_BEGIN = '; BEGIN Easy PHP Settings';

	/**
	 * Last line of the block this plugin manages.
	 */
	const MARKER_END = '; END Easy PHP Settings';

	/**
	 * First line written by versions before 1.1.9, which owned the whole file.
	 */
	const LEGACY_HEADER = '; PHP Settings generated by Easy PHP Settings plugin';

	/**
	 * Maximum size of a file this class will write.
	 */
	const MAX_CONTENT_BYTES = 1048576;

	/**
	 * Constructor
	 */
	private function __construct() {}

	/**
	 * Get directory path
	 *
	 * @return string
	 */
	public static function get_dir_path() {
		return ABSPATH;
	}

	/**
	 * Get INI file names
	 *
	 * @return array
	 */
	public static function get_ini_file_names() {
		return array(
			self::get_dir_path() . '.user.ini',
			self::get_dir_path() . 'php.ini',
		);
	}

	/* ─── Pure content helpers (no filesystem access) ─── */

	/**
	 * Insert or replace the plugin's managed block, keeping all other content.
	 *
	 * @param string $existing Current file content ('' when the file does not exist).
	 * @param string $body     Directives to place inside the managed block.
	 * @return string New file content.
	 */
	public static function merge_managed_block( $existing, $body ) {
		list( $before, $after ) = self::split_around_managed_block( (string) $existing );
		return self::join_sections( array( $before, self::build_block( (string) $body ), $after ) );
	}

	/**
	 * Remove the plugin's managed block, keeping all other content.
	 *
	 * @param string $existing Current file content.
	 * @return string Remaining content ('' when nothing else was in the file).
	 */
	public static function strip_managed_block( $existing ) {
		$existing                          = (string) $existing;
		list( $before, $after, $has_ours ) = self::split_around_managed_block( $existing );
		if ( ! $has_ours ) {
			return $existing;
		}
		return self::join_sections( array( $before, $after ) );
	}

	/**
	 * Split content into the foreign lines before and after the managed region.
	 *
	 * Handles three layouts: a proper marker block, a begin marker with no end
	 * (treated as ours to EOF), and a legacy pre-marker file (ours from the
	 * legacy header to EOF). In the last two, foreign "; Label" … "; END Label"
	 * blocks that sit inside the region are kept.
	 *
	 * @param string $content File content.
	 * @return array{0: string[], 1: string[], 2: bool} Lines before, lines after, whether a managed region was found.
	 */
	private static function split_around_managed_block( $content ) {
		$lines = self::split_lines( $content );
		$begin = self::find_line( $lines, self::MARKER_BEGIN, 0 );

		if ( false !== $begin ) {
			$end    = self::find_line( $lines, self::MARKER_END, $begin + 1 );
			$before = array_slice( $lines, 0, $begin );
			if ( false === $end ) {
				return array( $before, self::keep_foreign_blocks( array_slice( $lines, $begin + 1 ) ), true );
			}
			// Drop any duplicate managed blocks further down the file.
			list( $rest_before, $rest_after ) = self::split_around_managed_block( implode( "\n", array_slice( $lines, $end + 1 ) ) );
			return array( $before, array_merge( $rest_before, $rest_after ), true );
		}

		$legacy = self::find_line( $lines, self::LEGACY_HEADER, 0 );
		if ( false !== $legacy ) {
			return array(
				array_slice( $lines, 0, $legacy ),
				self::keep_foreign_blocks( array_slice( $lines, $legacy + 1 ) ),
				true,
			);
		}

		return array( $lines, array(), false );
	}

	/**
	 * Keep only "; Label" … "; END Label" blocks written by other tools.
	 *
	 * @param string[] $lines Lines from a region this plugin owns.
	 * @return string[]
	 */
	private static function keep_foreign_blocks( array $lines ) {
		$kept  = array();
		$count = count( $lines );

		for ( $i = 0; $i < $count; $i++ ) {
			$label = self::block_label( $lines[ $i ] );
			if ( null === $label ) {
				continue;
			}
			$end = self::find_line( $lines, '; END ' . $label, $i + 1 );
			if ( false === $end ) {
				continue;
			}
			if ( ! empty( $kept ) ) {
				$kept[] = '';
			}
			$kept = array_merge( $kept, array_slice( $lines, $i, $end - $i + 1 ) );
			$i    = $end;
		}

		return $kept;
	}

	/**
	 * Return the label of a "; Label" comment line, or null.
	 *
	 * @param string $line Line to inspect.
	 * @return string|null
	 */
	private static function block_label( $line ) {
		if ( ! preg_match( '/^;\s*(.+?)\s*$/', trim( $line ), $m ) ) {
			return null;
		}
		return 0 === stripos( $m[1], 'END ' ) ? null : $m[1];
	}

	/**
	 * Build the managed block, removing any marker lines from the body.
	 *
	 * @param string $body Directives.
	 * @return string[]
	 */
	private static function build_block( $body ) {
		$markers = array( self::MARKER_BEGIN, self::MARKER_END );
		$lines   = array_filter(
			self::split_lines( $body ),
			function ( $line ) use ( $markers ) {
				return ! in_array( trim( $line ), $markers, true );
			}
		);
		$lines   = self::trim_blank_edges( array_values( $lines ) );

		return array_merge( array( self::MARKER_BEGIN ), $lines, array( self::MARKER_END ) );
	}

	/**
	 * Join non-empty sections with one blank line between them.
	 *
	 * @param array<int, string[]> $sections Line arrays.
	 * @return string Content ending in a newline, or '' when all are empty.
	 */
	private static function join_sections( array $sections ) {
		$parts = array();
		foreach ( $sections as $section ) {
			$section = self::trim_blank_edges( $section );
			if ( ! empty( $section ) ) {
				$parts[] = implode( "\n", $section );
			}
		}
		return empty( $parts ) ? '' : implode( "\n\n", $parts ) . "\n";
	}

	/**
	 * Remove leading and trailing blank lines.
	 *
	 * @param string[] $lines Lines.
	 * @return string[]
	 */
	private static function trim_blank_edges( array $lines ) {
		while ( ! empty( $lines ) && '' === trim( $lines[0] ) ) {
			array_shift( $lines );
		}
		while ( ! empty( $lines ) && '' === trim( end( $lines ) ) ) {
			array_pop( $lines );
		}
		return $lines;
	}

	/**
	 * Split content into lines, accepting \n, \r\n and \r.
	 *
	 * @param string $content Content.
	 * @return string[]
	 */
	private static function split_lines( $content ) {
		if ( '' === $content ) {
			return array();
		}
		return preg_split( '/\r\n|\r|\n/', rtrim( $content, "\r\n" ) );
	}

	/**
	 * Find the first line equal to $needle (ignoring surrounding whitespace).
	 *
	 * @param string[] $lines  Lines.
	 * @param string   $needle Line to find.
	 * @param int      $offset Index to start at.
	 * @return int|false
	 */
	private static function find_line( array $lines, $needle, $offset ) {
		$count = count( $lines );
		for ( $i = $offset; $i < $count; $i++ ) {
			if ( trim( $lines[ $i ] ) === $needle ) {
				return $i;
			}
		}
		return false;
	}

	/* ─── Filesystem operations ─── */

	/**
	 * Initialise and return the WordPress filesystem, or null.
	 *
	 * @return WP_Filesystem_Base|null
	 */
	private static function filesystem() {
		global $wp_filesystem;
		if ( ! $wp_filesystem ) {
			require_once ABSPATH . 'wp-admin/includes/file.php';
			WP_Filesystem();
		}
		return $wp_filesystem ? $wp_filesystem : null;
	}

	/**
	 * Read a file, returning '' when it does not exist and false when unreadable.
	 *
	 * @param WP_Filesystem_Base $fs       Filesystem.
	 * @param string             $filepath Path.
	 * @return string|false
	 */
	private static function read_existing( $fs, $filepath ) {
		if ( ! $fs->exists( $filepath ) ) {
			return '';
		}
		return $fs->get_contents( $filepath );
	}

	/**
	 * Write a file via a temp file, then move it into place.
	 *
	 * @param WP_Filesystem_Base $fs       Filesystem.
	 * @param string             $filepath Path.
	 * @param string             $content  Content.
	 * @return bool
	 */
	private static function put_atomic( $fs, $filepath, $content ) {
		$temp_filepath = $filepath . '.tmp';
		if ( ! $fs->put_contents( $temp_filepath, $content ) ) {
			if ( $fs->exists( $temp_filepath ) ) {
				$fs->delete( $temp_filepath );
			}
			return false;
		}
		if ( ! $fs->move( $temp_filepath, $filepath, true ) ) {
			$fs->delete( $temp_filepath );
			return false;
		}
		$fs->chmod( $filepath, 0644 );
		return true;
	}

	/**
	 * Write the plugin's directives into each INI file, keeping other content.
	 *
	 * @param string $content The directives to place in the managed block.
	 * @return array|WP_Error Array of written filenames or WP_Error on failure.
	 */
	public static function write( $content ) {
		$fs = self::filesystem();
		if ( ! $fs ) {
			return new WP_Error( 'filesystem_unavailable', __( 'WordPress filesystem could not be initialised.', 'easy-php-settings' ) );
		}

		if ( strlen( $content ) > self::MAX_CONTENT_BYTES ) {
			return new WP_Error( 'content_too_large', __( 'Content exceeds maximum allowed size (1MB).', 'easy-php-settings' ) );
		}

		// File paths here are constants (ABSPATH . '.user.ini' / 'php.ini'),
		// not user-controlled — no path-traversal vector to defend against.
		if ( ! $fs->is_writable( self::get_dir_path() ) ) {
			return new WP_Error( 'directory_not_writable', __( 'Directory is not writable.', 'easy-php-settings' ) );
		}

		$files_written = array();

		foreach ( self::get_ini_file_names() as $filepath ) {
			$existing = self::read_existing( $fs, $filepath );
			if ( false === $existing ) {
				// Never overwrite a file we could not read: we would lose its content.
				Easy_Error_Handler::log_error( "Could not read {$filepath}; left unchanged.", 'write_ini_file', 'warning' );
				continue;
			}

			$merged = self::merge_managed_block( $existing, $content );
			if ( strlen( $merged ) > self::MAX_CONTENT_BYTES ) {
				Easy_Error_Handler::log_error( "Merged content for {$filepath} exceeds size limit; left unchanged.", 'write_ini_file', 'warning' );
				continue;
			}

			if ( self::put_atomic( $fs, $filepath, $merged ) ) {
				$files_written[] = basename( $filepath );
			} else {
				Easy_Error_Handler::log_error( "Could not write {$filepath}.", 'write_ini_file', 'warning' );
			}
		}

		return $files_written;
	}

	/**
	 * Remove the plugin's directives from each INI file.
	 *
	 * Files left empty are deleted; files with other content keep it.
	 *
	 * @return array|WP_Error Array of cleaned filenames or WP_Error on failure.
	 */
	public static function remove_files() {
		$fs = self::filesystem();
		if ( ! $fs ) {
			return new WP_Error( 'filesystem_unavailable', __( 'WordPress filesystem could not be initialised.', 'easy-php-settings' ) );
		}

		$files_cleaned = array();

		foreach ( self::get_ini_file_names() as $filepath ) {
			// Defensive: only ever touch the two files we manage. The list is
			// hardcoded, but this guards future refactors.
			$basename = basename( $filepath );
			if ( ! in_array( $basename, array( '.user.ini', 'php.ini' ), true ) ) {
				continue;
			}

			$existing = self::read_existing( $fs, $filepath );
			if ( '' === $existing || false === $existing ) {
				continue;
			}

			$remaining = self::strip_managed_block( $existing );
			if ( $remaining === $existing ) {
				continue;
			}

			$done = '' === $remaining
				? $fs->delete( $filepath )
				: self::put_atomic( $fs, $filepath, $remaining );

			if ( $done ) {
				$files_cleaned[] = $basename;
			} else {
				Easy_Error_Handler::log_error( "Could not clean {$filepath}.", 'remove_ini_file', 'warning' );
			}
		}

		return $files_cleaned;
	}

	/**
	 * Check if directory is writable
	 *
	 * @return bool
	 */
	public static function is_writable() {
		$fs = self::filesystem();
		return $fs ? $fs->is_writable( self::get_dir_path() ) : false;
	}
}
