<?php
/**
 * Tests for the marker-based merge of .user.ini / php.ini content.
 *
 * @package EasyPHPSettings
 */

use PHPUnit\Framework\TestCase;

/**
 * EasyIniFile::merge_managed_block() / strip_managed_block().
 */
class EasyIniFileMarkersTest extends TestCase {

	const WORDFENCE_BLOCK = "; Wordfence WAF\nauto_prepend_file = '/var/www/wordfence-waf.php'\n; END Wordfence WAF";

	const LEGACY_FILE = "; PHP Settings generated by Easy PHP Settings plugin\n; Created By H M Shahadul Islam\n; Generated on: 2026-06-20 16:14:07\n\nmemory_limit = 256M\nmax_input_vars = 10000\n";

	private function managed( $body ) {
		return EasyIniFile::MARKER_BEGIN . "\n" . $body . "\n" . EasyIniFile::MARKER_END;
	}

	public function test_writes_only_the_managed_block_into_an_empty_file() {
		$result = EasyIniFile::merge_managed_block( '', 'memory_limit = 256M' );

		$this->assertSame( $this->managed( 'memory_limit = 256M' ) . "\n", $result );
	}

	public function test_keeps_existing_foreign_content_and_appends_block() {
		$existing = self::WORDFENCE_BLOCK . "\n";

		$result = EasyIniFile::merge_managed_block( $existing, 'memory_limit = 256M' );

		$this->assertSame(
			self::WORDFENCE_BLOCK . "\n\n" . $this->managed( 'memory_limit = 256M' ) . "\n",
			$result
		);
	}

	public function test_replaces_existing_managed_block_in_place() {
		$existing = "upload_tmp_dir = /tmp\n\n"
			. $this->managed( 'memory_limit = 128M' ) . "\n\n"
			. self::WORDFENCE_BLOCK . "\n";

		$result = EasyIniFile::merge_managed_block( $existing, 'memory_limit = 512M' );

		$this->assertSame(
			"upload_tmp_dir = /tmp\n\n"
			. $this->managed( 'memory_limit = 512M' ) . "\n\n"
			. self::WORDFENCE_BLOCK . "\n",
			$result
		);
	}

	public function test_merging_twice_is_idempotent() {
		$once  = EasyIniFile::merge_managed_block( self::WORDFENCE_BLOCK, 'memory_limit = 256M' );
		$twice = EasyIniFile::merge_managed_block( $once, 'memory_limit = 256M' );

		$this->assertSame( $once, $twice );
	}

	public function test_legacy_file_is_replaced_but_foreign_blocks_inside_it_survive() {
		$existing = self::LEGACY_FILE . "\n" . self::WORDFENCE_BLOCK . "\n";

		$result = EasyIniFile::merge_managed_block( $existing, 'memory_limit = 512M' );

		$this->assertSame(
			$this->managed( 'memory_limit = 512M' ) . "\n\n" . self::WORDFENCE_BLOCK . "\n",
			$result
		);
	}

	public function test_legacy_file_keeps_content_written_before_the_legacy_header() {
		$existing = "date.timezone = UTC\n" . self::LEGACY_FILE;

		$result = EasyIniFile::merge_managed_block( $existing, 'memory_limit = 512M' );

		$this->assertSame(
			"date.timezone = UTC\n\n" . $this->managed( 'memory_limit = 512M' ) . "\n",
			$result
		);
	}

	public function test_marker_lines_inside_the_body_are_dropped() {
		$body = "memory_limit = 256M\n" . EasyIniFile::MARKER_END . "\nmax_input_vars = 5000";

		$result = EasyIniFile::merge_managed_block( '', $body );

		$this->assertSame(
			$this->managed( "memory_limit = 256M\nmax_input_vars = 5000" ) . "\n",
			$result
		);
	}

	public function test_begin_marker_without_end_drops_rest_but_keeps_foreign_blocks() {
		$existing = "date.timezone = UTC\n"
			. EasyIniFile::MARKER_BEGIN . "\nmemory_limit = 128M\n\n"
			. self::WORDFENCE_BLOCK . "\n";

		$result = EasyIniFile::merge_managed_block( $existing, 'memory_limit = 512M' );

		$this->assertSame(
			"date.timezone = UTC\n\n"
			. $this->managed( 'memory_limit = 512M' ) . "\n\n"
			. self::WORDFENCE_BLOCK . "\n",
			$result
		);
	}

	public function test_crlf_line_endings_are_handled() {
		$existing = str_replace( "\n", "\r\n", $this->managed( 'memory_limit = 128M' ) . "\n" . self::WORDFENCE_BLOCK . "\n" );

		$result = EasyIniFile::merge_managed_block( $existing, 'memory_limit = 512M' );

		$this->assertSame(
			$this->managed( 'memory_limit = 512M' ) . "\n\n" . self::WORDFENCE_BLOCK . "\n",
			$result
		);
	}

	public function test_strip_removes_only_the_managed_block() {
		$existing = self::WORDFENCE_BLOCK . "\n\n" . $this->managed( 'memory_limit = 256M' ) . "\n";

		$this->assertSame( self::WORDFENCE_BLOCK . "\n", EasyIniFile::strip_managed_block( $existing ) );
	}

	public function test_strip_returns_empty_string_when_file_held_only_our_block() {
		$existing = $this->managed( 'memory_limit = 256M' ) . "\n";

		$this->assertSame( '', EasyIniFile::strip_managed_block( $existing ) );
	}

	public function test_strip_of_legacy_file_returns_empty_string() {
		$this->assertSame( '', EasyIniFile::strip_managed_block( self::LEGACY_FILE ) );
	}

	public function test_strip_of_legacy_file_with_adjacent_foreign_blocks_keeps_both() {
		$other    = "; Other Tool\nzend.assertions = -1\n; END Other Tool";
		$existing = self::LEGACY_FILE . self::WORDFENCE_BLOCK . "\n" . $other . "\n";

		$this->assertSame(
			self::WORDFENCE_BLOCK . "\n\n" . $other . "\n",
			EasyIniFile::strip_managed_block( $existing )
		);
	}

	public function test_duplicate_managed_blocks_are_collapsed_into_one() {
		$existing = $this->managed( 'memory_limit = 128M' ) . "\n\n"
			. self::WORDFENCE_BLOCK . "\n\n"
			. $this->managed( 'memory_limit = 64M' ) . "\n";

		$result = EasyIniFile::merge_managed_block( $existing, 'memory_limit = 512M' );

		$this->assertSame(
			$this->managed( 'memory_limit = 512M' ) . "\n\n" . self::WORDFENCE_BLOCK . "\n",
			$result
		);
	}

	public function test_strip_leaves_unrelated_file_untouched() {
		$existing = "date.timezone = UTC\n";

		$this->assertSame( $existing, EasyIniFile::strip_managed_block( $existing ) );
	}
}
